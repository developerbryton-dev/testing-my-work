"""
src/utils.py
Utility functions and plot formatting setups.
"""

import matplotlib.pyplot as plt


def set_plot_style() -> None:
    """Configures default matplotlib plot styling for clean visualizations."""
    plt.style.use("seaborn-v0_8-whitegrid" if "seaborn-v0_8-whitegrid" in plt.style.available else "default")
    plt.rcParams.update({
        "font.size": 10,
        "axes.labelsize": 11,
        "axes.titlesize": 12,
        "xtick.labelsize": 9,
        "ytick.labelsize": 9,
        "legend.fontsize": 9,
        "figure.titlesize": 14,
    })